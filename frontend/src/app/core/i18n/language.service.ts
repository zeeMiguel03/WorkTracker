@Injectable({ providedIn: 'root' })
export class LanguageService {
  private static readonly storageKey = 'worktracker-language';
  private readonly document = inject(DOCUMENT);
  private readonly currentLanguage = signal<AppLanguage>(this.readLanguage());
  private pageTitle = '';

  readonly language = this.currentLanguage.asReadonly();
  readonly isEnglish = computed(() => this.currentLanguage() === 'en');
  readonly locale = computed(() => this.isEnglish() ? 'en-GB' : 'pt-PT');

  constructor() { this.applyLanguage(this.currentLanguage()); }

  toggle(): void { this.setLanguage(this.isEnglish() ? 'pt' : 'en'); }

  setLanguage(language: AppLanguage): void {
    this.currentLanguage.set(language);
    this.applyLanguage(language);
    try { window.localStorage.setItem(LanguageService.storageKey, language); } catch { /* Language still works without storage. */ }
  }

  setPageTitle(title: string): void {
    this.pageTitle = title;
    this.document.title = this.translate(title);
  }

  translate(value: string): string {
    return this.isEnglish() ? ENGLISH[value] ?? value : value;
  }

  private readLanguage(): AppLanguage {
    try { return window.localStorage.getItem(LanguageService.storageKey) === 'en' ? 'en' : 'pt'; } catch { return 'pt'; }
  }

  private applyLanguage(language: AppLanguage): void {
    this.document.documentElement.lang = language === 'en' ? 'en-GB' : 'pt-PT';
    if (this.pageTitle) this.document.title = this.translate(this.pageTitle);
  }
}
